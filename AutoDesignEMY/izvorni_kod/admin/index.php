<?php
/* Auto Design EMY – hidden administration for the gallery. */
declare(strict_types=1);
require __DIR__ . '/lib.php';
header('X-Robots-Tag: noindex, nofollow');
header('Cache-Control: no-store');
header("Content-Security-Policy: default-src 'self'; img-src 'self' data: blob:; media-src 'self' blob:; style-src 'self' 'unsafe-inline'; script-src 'self' 'unsafe-inline'; frame-ancestors 'none'");
start_session();

$action = $_POST['action'] ?? '';

/* ---------- login / logout ---------- */
if ($action === 'login') {
    check_csrf();
    if (too_many_attempts()) { flash('Previše pokušaja. Pokušajte ponovo za 15 minuta.', 'err'); redirect(); }
    $ok = hash_equals(ADMIN_USER, (string)($_POST['user'] ?? '')) & password_verify((string)($_POST['pass'] ?? ''), ADMIN_PASS_HASH);
    record_attempt((bool)$ok);
    if ($ok) {
        session_regenerate_id(true);
        $_SESSION['admin'] = true; $_SESSION['ua'] = $_SERVER['HTTP_USER_AGENT'] ?? '';
        redirect();
    }
    flash('Pogrešno korisničko ime ili lozinka.', 'err'); redirect();
}
if ($action === 'logout') { check_csrf(); $_SESSION = []; session_destroy(); redirect(); }

/* ---------- actions (logged in only) ---------- */
if ($action && is_logged_in()) {
    check_csrf();
    try {
        $items = load_items();
        $id = (string)($_POST['id'] ?? '');
        $i = $id !== '' ? find_index($items, $id) : -1;
        switch ($action) {
            case 'upload':
                $cat = array_key_exists($_POST['cat'] ?? '', CATS) ? $_POST['cat'] : 'wheels';
                $meta = ['cat' => $cat, 'cap_bs' => trim(mb_substr((string)($_POST['cap_bs'] ?? ''), 0, 140)),
                         'cap_en' => trim(mb_substr((string)($_POST['cap_en'] ?? ''), 0, 140)), 'featured' => !empty($_POST['featured'])];
                $item = handle_upload($_FILES['file'] ?? [], $meta, $_POST['poster'] ?? null);
                array_unshift($items, $item);               // newest first
                save_items($items);
                flash('Rad je dodan u galeriju.');
                break;
            case 'update':
                if ($i < 0) throw new RuntimeException('Stavka nije pronađena.');
                $items[$i]['cat'] = array_key_exists($_POST['cat'] ?? '', CATS) ? $_POST['cat'] : $items[$i]['cat'];
                $items[$i]['caption'] = array_filter(['bs' => trim(mb_substr((string)($_POST['cap_bs'] ?? ''), 0, 140)),
                                                      'en' => trim(mb_substr((string)($_POST['cap_en'] ?? ''), 0, 140))]);
                $items[$i]['featured'] = !empty($_POST['featured']);
                save_items($items);
                flash('Promjene su sačuvane.');
                break;
            case 'up': case 'down': case 'top':
                if ($i < 0) throw new RuntimeException('Stavka nije pronađena.');
                $to = $action === 'top' ? 0 : ($action === 'up' ? max(0, $i - 1) : min(count($items) - 1, $i + 1));
                $moved = array_splice($items, $i, 1);
                array_splice($items, $to, 0, $moved);
                save_items($items);
                break;
            case 'delete':
                if ($i < 0) throw new RuntimeException('Stavka nije pronađena.');
                delete_item_files($items[$i]);
                array_splice($items, $i, 1);
                save_items($items);
                flash('Rad je obrisan iz galerije.');
                break;
            case 'password':
                if (!password_verify((string)($_POST['current'] ?? ''), ADMIN_PASS_HASH)) throw new RuntimeException('Trenutna lozinka nije tačna.');
                $new = (string)($_POST['new'] ?? '');
                if (mb_strlen($new) < 10) throw new RuntimeException('Nova lozinka mora imati najmanje 10 znakova.');
                if ($new !== (string)($_POST['new2'] ?? '')) throw new RuntimeException('Nove lozinke se ne podudaraju.');
                $cfg = "<?php\n// Generated by the admin panel. Do not share this file.\nconst ADMIN_USER = " . var_export(ADMIN_USER, true) .
                       ";\nconst ADMIN_PASS_HASH = " . var_export(password_hash($new, PASSWORD_DEFAULT), true) . ";\n";
                if (file_put_contents(__DIR__ . '/config.php', $cfg, LOCK_EX) === false) throw new RuntimeException('Ne mogu snimiti novu lozinku.');
                flash('Lozinka je promijenjena.');
                break;
        }
    } catch (Throwable $e) {
        flash($e->getMessage(), 'err');
    }
    $anchor = ($action === 'up' || $action === 'down' || $action === 'top') ? '#item-' . rawurlencode($id) : '';
    redirect('index.php' . $anchor);
}
if ($action) redirect();

